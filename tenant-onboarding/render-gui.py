#!/usr/bin/env python3
"""neocloud — render the GUI act's CR files for tenant2 (owner 2026-11-12: "i should have both CR YAMLs at hand, tenant2
with and without internet").

  python3 tenant-onboarding/render-gui.py            writes tenant-onboarding/gui/tenant2.yaml + tenant-onboarding/gui/tenant2-internet.yaml

Each file = EVERY object the onboarding touches, as the full object you create or edit in the EDA GUI:
  1. the tenant's own objects        = templates/tenant.yaml.tftpl (the SAME template Terraform renders)
  2. the shared objects it edits      = the repo baseline (manifests/*.yaml) + the tenant2 additions (owner Q4 B)
  3. the GPU bookings                 = the GPU rail Interfaces with label backend=tenant2 (4 GPUs: the first 4 free ones of the
                                        baseline = GPU 5-8 of GPU Server 2, the same 4 Terraform picks with gpus = 4)
Terraform makes exactly these changes, but sends the shared edits + bookings as JSON patches (terraform/crs.tf).
"""
import pathlib
import re
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
M = HERE.parent / "manifests"
VARS = {"tenant": "tenant2", "subnet": "200.200.200.0/24", "prefix_len": "24",
        "gateway": "200.200.200.1/24", "vlan": "102"}
GPUS = [(2, 5), (2, 6), (2, 7), (2, 8)]   # (server, gpu): first 4 free GPUs of the baseline, Terraform's order


def render(text, v):
    """the subset of Terraform template syntax the template uses: whole-line %{ if x ~} / %{ else ~} / %{ endif ~},
    inline %{ if x }…%{ endif }, ${var}, escapes $${ and %%{"""
    out, stack = [], []
    for line in text.splitlines(keepends=True):
        d = re.fullmatch(r"\s*%\{ (if (\w+)|else|endif) ~\}\s*", line)
        if d:
            if d.group(1).startswith("if"):
                stack.append(bool(v[d.group(2)]))
            elif d.group(1) == "else":
                stack[-1] = not stack[-1]
            else:
                stack.pop()
            continue
        if all(stack):
            out.append(line)
    s = "".join(out)
    s = re.sub(r"%\{ if (\w+) \}(.*?)%\{ endif \}", lambda m: m.group(2) if v[m.group(1)] else "", s)
    s = re.sub(r"(?<!\$)\$\{(\w+)\}", lambda m: str(v[m.group(1)]), s)
    return s.replace("$${", "${").replace("%%{", "%{")


def docs(path):
    return [d for d in yaml.safe_load_all(path.read_text()) if d]


def find(path, kind, name):
    return next(d for d in docs(path) if d["kind"] == kind and d["metadata"]["name"] == name)


def dump(obj):
    return yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=140)


def build(internet):
    v = dict(VARS, internet=internet)
    t = v["tenant"]
    parts = [render((HERE / "templates/tenant.yaml.tftpl").read_text(), v)]
    shared = []
    be = find(M / "backend.yaml", "Backend", "gpu-backend")
    be["spec"]["gpuIsolationGroups"].append({"name": t, "interfaceSelectors": [f"role=gpu,backend={t}"]})
    shared.append(("EDIT Backend gpu-backend: gpuIsolationGroups += " + t, be))
    pol = find(M / "leaking.yaml", "Policy", "leak-shared-import")
    pol["spec"]["statements"].append({"name": t, "match": {"prefixSet": f"{t}-subnet"}, "action": {"policyResult": "Accept"}})
    shared.append((f"EDIT Policy leak-shared-import: statements += {t} (shared-services reaches {t})", pol))
    if internet:
        pol = find(M / "leaking.yaml", "Policy", "leak-internet-import")
        pol["spec"]["statements"].append({"name": t, "match": {"prefixSet": f"{t}-subnet"}, "action": {"policyResult": "Accept"}})
        shared.append((f"EDIT Policy leak-internet-import: statements += {t} (its subnet leaks into VRF internet)", pol))
        ps = find(M / "edge.yaml", "PrefixSet", "internet-public")
        ps["spec"]["prefixes"].append({"prefix": v["subnet"], "startRange": int(v["prefix_len"]), "endRange": int(v["prefix_len"])})
        shared.append((f"EDIT PrefixSet internet-public: prefixes += {v['subnet']} (border leaves + border routers announce it)", ps))
    gpus = []
    for s, g in GPUS:
        gpus.append((f"EDIT Interface rail-leaf-{g}-ethernet-1-{s} (GPU {g} of GPU Server {s}): label backend={t}", {
            "apiVersion": "interfaces.eda.nokia.com/v1", "kind": "Interface",
            "metadata": {"name": f"rail-leaf-{g}-ethernet-1-{s}", "namespace": "neocloud",
                         "labels": {"host": f"gpu-server-{s}", "rail": str(g), "role": "gpu", "backend": t}},
            "spec": {"enabled": True, "encapType": "Dot1q", "lldp": True, "type": "Interface",
                     "members": [{"enabled": True, "interface": f"ethernet-1-{s}", "lacpPortPriority": 32768,
                                  "node": f"rail-leaf-{g}"}]}}))
    head = f"""# GENERATED by tenant-onboarding/render-gui.py — edit templates/tenant.yaml.tftpl or the generator, not this file.
# neocloud tenant2 onboarding, GUI act ({'WITH' if internet else 'WITHOUT'} internet). Every object the onboarding touches:
#   NEW   PrefixSet {t}-subnet · Policy leak-{t}-export · Policy leak-{t}-import · VirtualNetwork {t}
#         (router {t}-vrf{', also on the DC1 border leaves' if internet else ''}, bridge domain, anycast gateway {v['gateway']}, VLAN {v['vlan']})
#   EDIT  {' · '.join(x[0].split(':')[0][5:] for x in shared)}
#   EDIT  {len(GPUS)} GPU rail Interfaces: add label backend={t} (= book the GPU for {t})
# GUI: create the NEW objects (YAML editor of each resource form, or Basket), edit the EDIT objects in their forms
# (the full edited object is below, the change is named above each one). Same result by CLI:
#   kubectl apply -f <this file>   (or edactl apply in the toolbox)
# Then the server side: bash hosts.sh gpu-server-2 (the booked GPUs' pods get their tenant2 frontend leg + rail /64).
# Remove again: revert the transaction(s) in the GUI (Transactions → Revert), then bash hosts.sh gpu-server-2.
"""
    body = parts[0].rstrip() + "\n"
    for title, obj in shared + gpus:
        body += f"---\n# {title}\n" + dump(obj)
    return head + body


def main():
    for internet, name in ((False, "tenant2.yaml"), (True, "tenant2-internet.yaml")):
        out = HERE / "gui" / name
        txt = build(internet)
        n = sum(1 for d in yaml.safe_load_all(txt) if d)
        out.write_text(txt)
        print(f"wrote {out} ({n} objects)")


if __name__ == "__main__":
    sys.exit(main())
